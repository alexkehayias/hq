fn upgrade_channel_created_by(conn: &Connection) -> Result<()> {
    if !has_column(conn, "channel", "created_by")? {
        conn.execute("ALTER TABLE channel ADD COLUMN created_by TEXT", [])?;
    }
    Ok(())
}

fn has_column(conn: &Connection, table: &str, column: &str) -> Result<bool> {
    let count: i64 = conn.query_row(
        "SELECT COUNT(*) FROM pragma_table_info(?1) WHERE name = ?2",
        rusqlite::params![table, column],
        |row| row.get(0),
    )?;
    Ok(count > 0)
}
