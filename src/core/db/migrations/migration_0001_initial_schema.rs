//! Baseline migration: the full current schema, plus the upgrades needed by
//! databases created before the migration framework existed.
//!
//! This migration is deliberately idempotent. A fresh database gets every table
//! from the `CREATE TABLE IF NOT EXISTS` statements. A database from before the
//! framework has no rows in `schema_migrations`, so this migration runs once
//! and the legacy upgrade functions bring its tables up to the current shape.
//!
//! Future schema changes belong in new migration modules, not here.

use super::MigrationFn;
use anyhow::Result;
use rusqlite::Connection;

pub const DOWN: Option<MigrationFn> = Some(down);

pub fn up(conn: &Connection) -> Result<()> {
    create_tables(conn)?;
    upgrade_note_meta(conn)?;
    upgrade_sessions(conn)?;
    upgrade_push_subscription(conn)?;
    upgrade_metric_event(conn)?;
    upgrade_loop_system_prompt(conn)?;
    upgrade_channel_created_by(conn)?;
    Ok(())
}

/// Drops everything this migration created. Rolling back the baseline leaves an
/// empty database; the framework removes the `schema_migrations` row itself.
pub fn down(conn: &Connection) -> Result<()> {
    conn.execute_batch(
        r#"
DROP TABLE IF EXISTS loop_run;
DROP TABLE IF EXISTS loop_emit_channel;
DROP TABLE IF EXISTS loop_channel;
DROP TABLE IF EXISTS loop;
DROP TABLE IF EXISTS channel;
DROP TABLE IF EXISTS eval_result;
DROP TABLE IF EXISTS eval_run;
DROP TABLE IF EXISTS session_tag;
DROP TABLE IF EXISTS tag;
DROP TABLE IF EXISTS chat_message;
DROP TABLE IF EXISTS session;
DROP TABLE IF EXISTS metric_event;
DROP TABLE IF EXISTS push_subscription;
DROP TABLE IF EXISTS auth;
DROP TABLE IF EXISTS vec_items;
DROP TABLE IF EXISTS note_meta;
"#,
    )?;
    Ok(())
}

fn create_tables(conn: &Connection) -> Result<()> {
    conn.execute_batch(
        r#"
CREATE TABLE IF NOT EXISTS note_meta (
    -- org-id of the note or hash of the title
    id TEXT PRIMARY KEY,
    -- Source file from storage directory
    file_name TEXT,
    -- Title of the note file or the heading
    title TEXT,
    -- Category
    category TEXT,
    -- Comma separated string of tags
    tags TEXT NULLABLE,
    -- Body of the note in markdown format
    body TEXT,
    -- Type of note e.g. note, meeting, task
    type TEXT DEFAULT 'note',
    -- Task status e.g. todo, done
    status TEXT,
    -- Task scheduled for date yyyy-mm-dd
    scheduled TEXT NULLABLE,
    -- Task deadline date yyyy-mm-dd
    deadline TEXT NULLABLE,
    -- Task closed date yyyy-mm-dd
    closed TEXT NULLABLE,
    -- Meeting date yyyy-mm-dd
    date TEXT NULLABLE,
    -- When the indexer last updated the row; NULL until the row is
    -- re-indexed, which lets the indexing upserts report newness
    index_updated_at TEXT NULLABLE
);

CREATE VIRTUAL TABLE IF NOT EXISTS vec_items USING vec0(
    note_meta_id TEXT PRIMARY KEY,
    embedding float[384]
);

CREATE TABLE IF NOT EXISTS auth (
    -- This should be the username or email address
    id TEXT PRIMARY KEY,
    -- Name of the service e.g. google
    service TEXT,
    refresh_token TEXT
);

CREATE TABLE IF NOT EXISTS push_subscription (
    -- Endpoint for the notification service uniquely identifies the client
    endpoint TEXT PRIMARY KEY,
    -- Public key of the client
    p256dh TEXT NOT NULL,
    -- Private key for encrypting notifications
    auth TEXT NOT NULL,
    encoding TEXT NOT NULL DEFAULT 'Aes126Gcm',
    -- Whether the subscription is still valid (not expired/invalid)
    is_valid INTEGER NOT NULL DEFAULT 1
);

CREATE TABLE IF NOT EXISTS session (
    -- Session ID is a UUID generated by the client
    id TEXT PRIMARY KEY,
    -- Timestamp of when the session was created
    created_at TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ', 'now')),
    -- Title of the session
    title TEXT,
    -- Summary text for the session
    summary TEXT,
    -- Mode of the session: 'chat' or 'agent'
    mode TEXT NOT NULL DEFAULT 'chat'
);

CREATE TABLE IF NOT EXISTS chat_message (
    -- UUID for the message (generated if not provided)
    id TEXT DEFAULT (lower(
       hex(randomblob(4)) || '-' ||
       hex(randomblob(2)) || '-4' ||
       substr(hex(randomblob(2)),2) || '-' ||
       substr('89ab', abs(random()) % 4 + 1, 1) ||
       substr(hex(randomblob(2)),2) || '-' ||
       hex(randomblob(6))
      )),
    -- Session ID is a UUID generated by the client
    session_id TEXT NOT NULL REFERENCES session(id),
    -- JSON encoded message data
    data TEXT NOT NULL,
    PRIMARY KEY (id)
);

CREATE TABLE IF NOT EXISTS tag (
    -- Primary key for the tag
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    -- Name of the tag
    name TEXT NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS session_tag (
    -- Foreign key to session table
    session_id TEXT NOT NULL REFERENCES session(id),
    -- Foreign key to tag table
    tag_id INTEGER NOT NULL REFERENCES tag(id),
    -- Primary key constraint for the composite key
    PRIMARY KEY (session_id, tag_id)
);

CREATE TABLE IF NOT EXISTS metric_event (
    -- Legacy columns, kept nullable so pre-bucket data stays readable.
    -- Older events populated `name` with a metric identifier (e.g. "token-count")
    -- and `value` with an aggregate count; new events populate the bucket
    -- columns below instead.
    name TEXT,
    timestamp TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ', 'now')),
    value INTEGER,
    -- Token buckets posted by upstream LLM providers. Legacy rows have
    -- 0 in all buckets (see upgrade_metric_event); new events populate these.
    input INTEGER NOT NULL DEFAULT 0,
    output INTEGER NOT NULL DEFAULT 0,
    cache_read INTEGER NOT NULL DEFAULT 0,
    cache_write INTEGER NOT NULL DEFAULT 0,
    reasoning INTEGER
);

CREATE INDEX IF NOT EXISTS metric_event_timestamp_idx ON metric_event(timestamp);

CREATE TABLE IF NOT EXISTS channel (
    -- Channel ID (alphanumeric with dashes/underscores)
    id TEXT PRIMARY KEY,
    -- How the channel is served: 'socket' (external Unix-socket publisher) or
    -- 'server' (in-process publisher, e.g. timer channels and webhooks)
    source TEXT NOT NULL,
    -- Debounce window (ms) for coalescing a channel's line burst into one event
    debounce_ms INTEGER NOT NULL DEFAULT 250,
    -- Session/agent that created the channel, if any; NULL for server- and
    -- socket-defined channels. Only this owner may emit to the channel.
    created_by TEXT,
    -- Creation timestamp
    created_at TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ', 'now'))
);

CREATE TABLE IF NOT EXISTS loop (
    -- UUID identifying the loop (also used as its bash session id)
    id TEXT PRIMARY KEY,
    -- System prompt for the per-event chat
    system_prompt TEXT NOT NULL,
    -- JSON array of tool names available to the per-event chat
    tools TEXT NOT NULL,
    -- Creation timestamp
    created_at TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ', 'now'))
);

CREATE TABLE IF NOT EXISTS loop_channel (
    -- Foreign key to loop table
    loop_id TEXT NOT NULL REFERENCES loop(id),
    -- Foreign key to channel table
    channel_id TEXT NOT NULL REFERENCES channel(id),
    -- Position preserves subscription order
    position INTEGER NOT NULL,
    -- Primary key constraint for the composite key
    PRIMARY KEY (loop_id, channel_id)
);

CREATE TABLE IF NOT EXISTS loop_emit_channel (
    -- Foreign key to loop table
    loop_id TEXT NOT NULL REFERENCES loop(id),
    -- Foreign key to channel table
    channel_id TEXT NOT NULL REFERENCES channel(id),
    -- Primary key constraint for the composite key
    PRIMARY KEY (loop_id, channel_id)
);

CREATE TABLE IF NOT EXISTS loop_run (
    -- UUID identifying this run
    id TEXT PRIMARY KEY,
    -- Foreign key to loop table
    loop_id TEXT NOT NULL REFERENCES loop(id),
    -- Channel that delivered the event
    channel_id TEXT NOT NULL,
    -- The event payload the loop received
    event TEXT NOT NULL,
    -- running | success | error | interrupted
    status TEXT NOT NULL,
    -- Chat session holding this run's transcript
    session_id TEXT NOT NULL,
    started_at TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ', 'now')),
    finished_at TEXT,
    duration_ms INTEGER,
    response TEXT,
    error TEXT
);

CREATE INDEX IF NOT EXISTS loop_run_loop_started_idx
    ON loop_run(loop_id, started_at DESC);

CREATE TABLE IF NOT EXISTS eval_run (
    id TEXT PRIMARY KEY,
    name TEXT NOT NULL,
    model TEXT NOT NULL,
    status TEXT,
    started_at TEXT,
    completed_at TEXT
);

CREATE TABLE IF NOT EXISTS eval_result (
    id TEXT PRIMARY KEY,
    run_id TEXT NOT NULL REFERENCES eval_run(id),
    case_id TEXT NOT NULL,
    input TEXT NOT NULL,
    output TEXT,
    passed INTEGER NOT NULL,
    error TEXT
);
"#,
    )?;
    Ok(())
}

/// Upgrades a `note_meta` table that predates the task columns.
///
/// 2024-12-29 added `type` and `status`; 2025-03-30 added `category`;
/// 2025-04-05 added `scheduled`, `deadline`, `closed`, and `date`;
/// 2026-10-29 added `index_updated_at`.
fn upgrade_note_meta(conn: &Connection) -> Result<()> {
    if !has_column(conn, "note_meta", "type")? {
        // The oldest tables also lack `category`, which the rebuild selects.
        if !has_column(conn, "note_meta", "category")? {
            conn.execute("ALTER TABLE note_meta ADD COLUMN category TEXT", [])?;
        }

        conn.execute_batch(
            r#"
DROP TABLE IF EXISTS note_meta_new;

CREATE TABLE note_meta_new (
    id TEXT PRIMARY KEY,
    file_name TEXT,
    title TEXT,
    category TEXT,
    tags TEXT NULLABLE,
    body TEXT,
    type TEXT DEFAULT 'note',
    status TEXT,
    scheduled TEXT NULLABLE,
    deadline TEXT NULLABLE,
    closed TEXT NULLABLE,
    date TEXT NULLABLE
);

INSERT INTO note_meta_new (id, file_name, title, category, tags, body)
SELECT id, file_name, title, category, tags, body FROM note_meta;

DROP TABLE note_meta;

ALTER TABLE note_meta_new RENAME TO note_meta;
"#,
        )?;
    }

    if !has_column(conn, "note_meta", "index_updated_at")? {
        conn.execute("ALTER TABLE note_meta ADD COLUMN index_updated_at TEXT", [])?;
    }

    Ok(())
}

/// Upgrades the session and chat_message tables.
///
/// 2025-11-26 added the `session` table; 2025-11-28 added `title` and
/// `summary`; 2026-02-21 added `mode`; 2026-03-07 gave `chat_message` a UUID
/// `id`.
fn upgrade_sessions(conn: &Connection) -> Result<()> {
    if !has_column(conn, "session", "title")? {
        conn.execute("ALTER TABLE session ADD COLUMN title TEXT", [])?;
    }
    if !has_column(conn, "session", "summary")? {
        conn.execute("ALTER TABLE session ADD COLUMN summary TEXT", [])?;
    }
    if !has_column(conn, "session", "mode")? {
        conn.execute(
            "ALTER TABLE session ADD COLUMN mode TEXT NOT NULL DEFAULT 'chat'",
            [],
        )?;
    }

    // Backfill sessions for chat messages that predate the session table.
    conn.execute_batch(
        "INSERT OR IGNORE INTO session (id)
         SELECT DISTINCT session_id FROM chat_message WHERE session_id IS NOT NULL;",
    )?;

    if !has_column(conn, "chat_message", "id")? {
        conn.execute_batch(
            r#"
DROP TABLE IF EXISTS chat_message_new;

CREATE TABLE chat_message_new (
    id TEXT DEFAULT (lower(
       hex(randomblob(4)) || '-' ||
       hex(randomblob(2)) || '-4' ||
       substr(hex(randomblob(2)),2) || '-' ||
       substr('89ab', abs(random()) % 4 + 1, 1) ||
       substr(hex(randomblob(2)),2) || '-' ||
       hex(randomblob(6))
      )),
    session_id TEXT NOT NULL REFERENCES session(id),
    data TEXT NOT NULL,
    PRIMARY KEY (id)
);

INSERT INTO chat_message_new (session_id, data)
SELECT session_id, data FROM chat_message;

DROP TABLE chat_message;

ALTER TABLE chat_message_new RENAME TO chat_message;
"#,
        )?;
    }

    Ok(())
}

