/// 2026-07-09 replaced the aggregate `{name, value}` metric payload with
/// structured token buckets. Legacy rows keep `name`/`value`; the new bucket
/// columns default to 0 so they don't skew bucket aggregations.
fn upgrade_metric_event(conn: &Connection) -> Result<()> {
    if !has_column(conn, "metric_event", "input")? {
        conn.execute_batch(
            r#"
DROP TABLE IF EXISTS metric_event_new;

CREATE TABLE metric_event_new (
    name TEXT,
    timestamp TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ', 'now')),
    value INTEGER,
    input INTEGER NOT NULL DEFAULT 0,
    output INTEGER NOT NULL DEFAULT 0,
    cache_read INTEGER NOT NULL DEFAULT 0,
    cache_write INTEGER NOT NULL DEFAULT 0,
    reasoning INTEGER
);

INSERT INTO metric_event_new (name, timestamp, value)
SELECT name, timestamp, value FROM metric_event;

DROP TABLE metric_event;

ALTER TABLE metric_event_new RENAME TO metric_event;

CREATE INDEX IF NOT EXISTS metric_event_timestamp_idx ON metric_event(timestamp);
"#,
        )?;
    }
    Ok(())
}

/// 2026-10-16 made `loop.system_prompt` required. It used to be nullable with a
/// generic built-in default substituted at runtime, but that default only
/// described event plumbing, not the task, so a promptless loop could not do
/// anything useful. Loops without a prompt are dropped rather than backfilled.
fn upgrade_loop_system_prompt(conn: &Connection) -> Result<()> {
    let nullable: bool = conn
        .query_row(
            "SELECT \"notnull\" = 0 FROM pragma_table_info('loop') WHERE name = 'system_prompt'",
            [],
            |row| row.get(0),
        )
        .unwrap_or(false);

    if nullable {
        conn.execute_batch(
            r#"
DROP TABLE IF EXISTS loop_new;

DELETE FROM loop_channel
 WHERE loop_id IN (SELECT id FROM loop WHERE system_prompt IS NULL);

DELETE FROM loop WHERE system_prompt IS NULL;

CREATE TABLE loop_new (
    id TEXT PRIMARY KEY,
    system_prompt TEXT NOT NULL,
    tools TEXT NOT NULL,
    created_at TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ', 'now'))
);

INSERT INTO loop_new (id, system_prompt, tools, created_at)
SELECT id, system_prompt, tools, created_at FROM loop;

DROP TABLE loop;

ALTER TABLE loop_new RENAME TO loop;
"#,
        )?;
    }

    Ok(())
}

/// 2026-10-18 added `channel.created_by`, the session/agent that created an
