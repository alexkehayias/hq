//! A small SQLite migration framework.
//!
//! A migration is a Rust module that exposes an `up` function and a `DOWN`
//! constant holding an optional `down` function, both operating on a
//! [`rusqlite::Connection`]. Modules are discovered by `build.rs` from their
//! `migration_<version>_<name>.rs` filenames, so there is no registry to
//! maintain by hand. The set of migrations applied to a database is recorded in
//! the `schema_migrations` table, so [`migrate`] runs only the pending ones and
//! [`rollback`] runs the most recent ones in reverse order.
//!
//! Each migration runs inside its own transaction and is recorded in the same
//! transaction, so a failure leaves the database at the previous migration.

use anyhow::{Context, Result, bail};
use rusqlite::Connection;
use std::collections::HashSet;

/// The signature of a migration's `up` or `down` function.
pub type MigrationFn = fn(&Connection) -> Result<()>;

/// A single schema migration.
#[derive(Debug, Clone)]
pub struct Migration {
    /// Monotonically increasing version. This is the primary key in
    /// `schema_migrations`.
    pub version: i64,
    /// Human-readable name, stored alongside the version.
    pub name: &'static str,
    /// Applies the migration.
    pub up: MigrationFn,
    /// Reverses the migration. `None` for migrations that cannot be undone.
    pub down: Option<MigrationFn>,
}

// Generated by `build.rs` from the `migration_*.rs` files in this directory.
// It declares the migration modules and defines `all()`.
include!(concat!(env!("OUT_DIR"), "/migrations.rs"));

/// A migration recorded as applied to a database.
#[derive(Debug, Clone)]
pub struct AppliedMigration {
    pub version: i64,
    pub name: String,
    pub applied_at: String,
}

/// The applied and pending migrations for a database.
#[derive(Debug)]
pub struct Status {
    pub applied: Vec<AppliedMigration>,
    pub pending: Vec<Migration>,
}

/// Checks that the migration registry is well-formed.
///
/// This verifies that versions are positive, unique, and registered in
/// ascending order, that names are snake_case, and that `HEAD` points at the
/// newest migration. Every runner calls it before touching the database, so a
/// bad registry fails loudly instead of applying migrations out of order.
pub fn validate() -> Result<()> {
    let migrations = all();
    validate_registry(&migrations)?;

    let latest = migrations
        .last()
        .expect("validate_registry rejects empty registries");
    let expected = format!("migration_{:04}_{}", latest.version, latest.name);
    let head = include_str!("HEAD").trim();
    if head != expected {
        bail!(
            "src/core/db/migrations/HEAD points at {head}, but the newest migration is {expected}; \
             update HEAD to point at {expected}"
        );
    }

    Ok(())
}

fn validate_registry(migrations: &[Migration]) -> Result<()> {
    let Some(first) = migrations.first() else {
        bail!("no migrations are registered");
    };
    if first.version <= 0 {
        bail!(
            "migration {} ({}) must have a positive version",
            first.version,
            first.name
        );
    }

    for window in migrations.windows(2) {
        let previous = &window[0];
        let migration = &window[1];
        if migration.version == previous.version {
            bail!(
                "migrations {} ({}) and {} ({}) share the same version",
                previous.version,
                previous.name,
                migration.version,
                migration.name
            );
        }
        if migration.version < previous.version {
            bail!(
                "migration {} ({}) is registered after migration {} ({}); versions must ascend",
                migration.version,
                migration.name,
                previous.version,
                previous.name
            );
        }
    }

    for migration in migrations {
        validate_name(migration)?;
    }

    Ok(())
}

fn validate_name(migration: &Migration) -> Result<()> {
    let name = migration.name;
    let valid = name.starts_with(|c: char| c.is_ascii_lowercase())
        && name
            .chars()
            .all(|c| c.is_ascii_lowercase() || c.is_ascii_digit() || c == '_');
    if !valid {
        bail!(
            "migration {} has invalid name {name:?}; use snake_case (lowercase letters, digits, underscores)",
            migration.version
        );
    }
    Ok(())
}

/// Converts a migration error into the error type used by `tokio_rusqlite`.
///
/// Migration functions use `anyhow` for readable context; callers that run
/// them inside [`tokio_rusqlite::Connection::call`] need this conversion.
pub fn db_error(err: anyhow::Error) -> tokio_rusqlite::Error {
    tokio_rusqlite::Error::Other(err.into())
}

const MIGRATIONS_TABLE: &str = "schema_migrations";

fn ensure_table(conn: &Connection) -> Result<()> {
    conn.execute_batch(&format!(
        "CREATE TABLE IF NOT EXISTS {MIGRATIONS_TABLE} (
            version INTEGER PRIMARY KEY,
            name TEXT NOT NULL,
            applied_at TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ', 'now'))
        );"
    ))?;
    Ok(())
}

/// Returns the migrations recorded as applied, oldest first.
fn applied(conn: &Connection) -> Result<Vec<AppliedMigration>> {
    ensure_table(conn)?;
    let mut stmt = conn.prepare(&format!(
        "SELECT version, name, applied_at FROM {MIGRATIONS_TABLE} ORDER BY version"
    ))?;
    let rows = stmt.query_map([], |row| {
        Ok(AppliedMigration {
            version: row.get(0)?,
            name: row.get(1)?,
            applied_at: row.get(2)?,
        })
    })?;

    let mut migrations = Vec::new();
    for row in rows {
        migrations.push(row?);
    }
    Ok(migrations)
}

/// Applies every pending migration, in version order.
///
/// Returns the migrations that ran. If there are none, this is a no-op.
pub fn migrate(conn: &Connection) -> Result<Vec<Migration>> {
    validate()?;
    let applied = applied(conn)?;
    let applied_versions: HashSet<i64> = applied.iter().map(|m| m.version).collect();
    let known_versions: HashSet<i64> = all().iter().map(|m| m.version).collect();

    // Refuse to run against a database that has seen a migration this build
    // does not know about. This usually means the binary is older than the
    // database, and continuing could corrupt the schema.
    if let Some(unknown) = applied
        .iter()
        .find(|m| !known_versions.contains(&m.version))
    {
        bail!(
            "database contains migration {} ({}) that this build does not know about",
            unknown.version,
            unknown.name
        );
    }

    let pending: Vec<Migration> = all()
        .into_iter()
        .filter(|m| !applied_versions.contains(&m.version))
        .collect();

    // A migration inserted below an already-applied one would be skipped
    // forever. Fail loudly instead of leaving a silently incomplete schema.
    let latest = applied.iter().map(|m| m.version).max().unwrap_or(0);
    if let Some(out_of_order) = pending.iter().find(|m| m.version < latest) {
        bail!(
            "migration {} ({}) is older than the latest applied migration ({})",
            out_of_order.version,
            out_of_order.name,
            latest
        );
    }

    if pending.is_empty() {
        return Ok(pending);
    }

    with_foreign_keys_disabled(conn, || {
        for migration in &pending {
            let tx = conn.unchecked_transaction()?;
            (migration.up)(&tx).with_context(|| {
                format!(
                    "migration {} ({}) failed",
                    migration.version, migration.name
                )
            })?;
            tx.execute(
                &format!("INSERT INTO {MIGRATIONS_TABLE} (version, name) VALUES (?1, ?2)"),
                rusqlite::params![migration.version, migration.name],
            )?;
            tx.commit()?;
        }
        Ok(())
    })?;

    Ok(pending)
}

/// Rolls back the most recent `steps` migrations, newest first.
///
/// Every target is checked for reversibility before anything runs. Each
/// migration then rolls back in its own transaction, so a failure part-way
/// leaves the migrations that already rolled back recorded as such.
pub fn rollback(conn: &Connection, steps: usize) -> Result<Vec<Migration>> {
    validate()?;
    let applied = applied(conn)?;
    let registry = all();

    let targets: Vec<AppliedMigration> = applied.into_iter().rev().take(steps).collect();
    if targets.is_empty() {
        bail!("no applied migrations to roll back");
    }

    let mut migrations = Vec::with_capacity(targets.len());
    for target in &targets {
        let migration = registry
            .iter()
            .find(|m| m.version == target.version)
            .with_context(|| {
                format!(
                    "cannot roll back migration {} ({}): not known to this build",
                    target.version, target.name
                )
            })?
            .clone();
        if migration.down.is_none() {
            bail!(
                "migration {} ({}) is not reversible",
                migration.version,
                migration.name
            );
        }
        migrations.push(migration);
    }

    with_foreign_keys_disabled(conn, || {
        for migration in &migrations {
            let down = migration.down.expect("checked above");
            let tx = conn.unchecked_transaction()?;
            down(&tx).with_context(|| {
                format!(
                    "rollback of migration {} ({}) failed",
                    migration.version, migration.name
                )
            })?;
            tx.execute(
                &format!("DELETE FROM {MIGRATIONS_TABLE} WHERE version = ?1"),
                [migration.version],
            )?;
            tx.commit()?;
        }
        Ok(())
    })?;

    Ok(migrations)
}

/// Reports which migrations are applied and which are still pending.
pub fn status(conn: &Connection) -> Result<Status> {
    validate()?;
    let applied = applied(conn)?;
    let applied_versions: HashSet<i64> = applied.iter().map(|m| m.version).collect();
    let pending = all()
        .into_iter()
        .filter(|m| !applied_versions.contains(&m.version))
        .collect();
    Ok(Status { applied, pending })
}

/// Runs `f` with foreign key enforcement disabled.
///
/// Table rebuilds drop tables that other tables reference, and SQLite checks
/// those references at statement time. Migrations are responsible for ending
/// with a consistent schema; the check is restored before returning.
fn with_foreign_keys_disabled<T>(conn: &Connection, f: impl FnOnce() -> Result<T>) -> Result<T> {
    let enabled: bool = conn
        .query_row("PRAGMA foreign_keys", [], |row| row.get::<_, i64>(0))
        .map(|value| value != 0)
        .unwrap_or(false);

    if enabled {
        conn.execute_batch("PRAGMA foreign_keys=OFF;")?;
    }

    let result = f();

    if enabled {
        match conn.execute_batch("PRAGMA foreign_keys=ON;") {
            Ok(()) => {}
            Err(err) if result.is_ok() => return Err(err.into()),
            Err(_) => {}
        }
    }

    result
}

#[cfg(test)]
mod tests {
    use super::*;

    fn migration(version: i64, name: &'static str) -> Migration {
        Migration {
            version,
            name,
            up: |_| Ok(()),
            down: None,
        }
    }

    /// The real registry must be valid, including `HEAD` pointing at the
    /// newest migration. Two branches that add migrations both edit `HEAD`, so
    /// merging them conflicts instead of leaving two diverging heads.
    #[test]
    fn validate_accepts_the_registry() {
        validate().unwrap();
    }

    #[test]
    fn validate_rejects_duplicate_versions() {
        let migrations = [migration(1, "first"), migration(1, "second")];
        let err = validate_registry(&migrations).unwrap_err();
        assert!(err.to_string().contains("share the same version"), "{err}");
    }

    #[test]
    fn validate_rejects_descending_versions() {
        let migrations = [migration(2, "second"), migration(1, "first")];
        let err = validate_registry(&migrations).unwrap_err();
        assert!(err.to_string().contains("versions must ascend"), "{err}");
    }

    #[test]
    fn validate_rejects_non_positive_versions() {
        let migrations = [migration(0, "zero")];
        let err = validate_registry(&migrations).unwrap_err();
        assert!(err.to_string().contains("positive version"), "{err}");
    }

    #[test]
    fn validate_rejects_invalid_names() {
        let migrations = [migration(1, "NotSnakeCase")];
        let err = validate_registry(&migrations).unwrap_err();
        assert!(err.to_string().contains("snake_case"), "{err}");
    }

    #[test]
    fn validate_rejects_empty_registry() {
        let err = validate_registry(&[]).unwrap_err();
        assert!(err.to_string().contains("no migrations"), "{err}");
    }
}
